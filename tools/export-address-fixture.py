#!/usr/bin/env python3
"""Export a small fixture for the Kotlin offline-address tests.

    tools/export-address-fixture.py data/tn/addresses.sqlite OUT.json \
        "1000 broadway, nashville" "500 deaderick st|36.1627,-86.7816" ...

For each query (optionally "|lat,lon" for --near) this runs the reference
search in tools/query-address.py against the full pack and records:
  * the expected results (what the Kotlin port must return), and
  * only the database rows the search touched: every street row returned by a
    prefix scan, plus, for each candidate street, the exact-number rows and the
    nearest lower/higher numbers (same parity and any parity).
The Kotlin test replays these rows through an in-memory AddressStore. Because
the nearest rows from the full table are included, the subset gives the same
interpolation answers as the full pack. Standard library only.
"""

import importlib.util
import json
import os
import sqlite3
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location("qa", os.path.join(HERE, "query-address.py"))
qa = importlib.util.module_from_spec(spec)
spec.loader.exec_module(qa)


def main():
    pack, out_path, queries = sys.argv[1], sys.argv[2], sys.argv[3:]
    db = sqlite3.connect(f"file:{pack}?mode=ro", uri=True)
    streets = {}
    houses = []  # (street_id, (number, num, unit))

    orig_candidates = qa.street_candidates
    orig_lookup = qa.lookup_number

    def rec_candidates(d, q, postcode):
        rows = orig_candidates(d, q, postcode)
        for r in rows:
            streets[r[0]] = r
        return rows

    def rec_lookup(d, street_id, house):
        houses.append((street_id, house))
        return orig_lookup(d, street_id, house)

    qa.street_candidates = rec_candidates
    qa.lookup_number = rec_lookup

    cases = []
    for item in queries:
        text, _, near_s = item.partition("|")
        near = tuple(float(v) for v in near_s.split(",")) if near_s else None
        res = qa.search(db, text, near, 5)
        cases.append({
            "text": text,
            "near": list(near) if near else None,
            "expected": [{k: r[k] for k in ("type", "lat", "lon", "label", "detail", "street_id")} for r in res],
        })

    addr = set()
    for sid, (number, num, unit) in houses:
        if num < 0:
            continue
        for row in db.execute("SELECT num, number, unit, lat, lon FROM addr WHERE street_id=? AND num=? AND number=?",
                              (sid, num, number)):
            addr.add((sid,) + row)
        for parity in (" AND num % 2 = ?", ""):
            args = (num % 2,) if parity else ()
            for sql in ("SELECT num, number, unit, lat, lon FROM addr WHERE street_id=? AND num>=0 AND num<?"
                        + parity + " ORDER BY num DESC LIMIT 1",
                        "SELECT num, number, unit, lat, lon FROM addr WHERE street_id=? AND num>?"
                        + parity + " ORDER BY num ASC LIMIT 1"):
                row = db.execute(sql, (sid, num) + args).fetchone()
                if row:
                    addr.add((sid,) + row)

    out = {
        "note": "Generated by tools/export-address-fixture.py from the Overture/NAD Tennessee pack; "
                "rows are a subset sufficient to replay these queries.",
        "streets": [list(r) for r in sorted(streets.values())],
        "addr": [list(a) for a in sorted(addr)],
        "cases": cases,
    }
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(out, f, ensure_ascii=False, separators=(",", ":"))
    print(f"{out_path}: {len(streets)} streets, {len(addr)} addr rows, {len(cases)} cases")


if __name__ == "__main__":
    main()
